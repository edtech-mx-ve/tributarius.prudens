def _paths() -> list[Path]:
    return [
        TARIFF_DIR
        / f"isr_monthly_lisr_article_106_2026_{month:02d}.json"
        for month in range(1, 13)
    ]


def test_article_106_2026_has_exactly_twelve_monthly_tariffs() -> None:
    paths = _paths()

    assert all(path.is_file() for path in paths)

    discovered = sorted(
        TARIFF_DIR.glob(
            "isr_monthly_lisr_article_106_2026_*.json"
        )
    )

    assert discovered == paths


def test_article_106_2026_controlled_values_match_anexo_8() -> None:
    registry = load_isr_tariff_registry(_paths())

    for month in range(1, 13):
        tariff = registry.select_for_fiscal_use(
            2026,
            ISRPeriod.MONTHLY,
            month,
        )

        assert tariff.version == (
            f"RMF-ANEXO8-2026-ART106-M{month:02d}"
        )
        assert tariff.fiscal_year == 2026
        assert tariff.period == ISRPeriod.MONTHLY
        assert tariff.month == month
        assert tariff.tariff_scope.value == "year_to_month"
        assert tariff.normative_ref == "lisr:articulo_106"
        assert len(tariff.brackets) == 11

        expected_rows = EXPECTED[month]

        for bracket, expected, rate in zip(
            tariff.brackets,
            expected_rows,
            RATES,
            strict=True,
        ):
            lower, upper, fixed = expected

            assert bracket.lower_limit == Decimal(lower)
            assert bracket.upper_limit == (
                None
                if upper is None
                else Decimal(upper)
            )
            assert bracket.fixed_fee == Decimal(fixed)
            assert bracket.rate_percent == Decimal(rate)


def test_article_106_2026_tariffs_preserve_legal_provenance() -> None:
    registry = load_isr_tariff_registry(_paths())

    for month in range(1, 13):
        tariff = registry.select_for_fiscal_use(
            2026,
            ISRPeriod.MONTHLY,
            month,
        )

        metadata = tariff.legal_metadata
        assert metadata is not None

        assert metadata.source_document_id == (
            "anexo_8_rmf_2026"
        )
        assert metadata.legal_basis_refs == [
            "lisr:articulo_106"
        ]
        assert metadata.publication_date is not None
        assert metadata.publication_date.isoformat() == (
            "2025-12-28"
        )
        assert metadata.effective_from is not None
        assert metadata.effective_from.isoformat() == (
            "2026-01-01"
        )
        assert metadata.effective_to is not None
        assert metadata.effective_to.isoformat() == (
            "2026-12-31"
        )
        assert metadata.validity_status.value == (
            "verified_in_force"
        )
        assert metadata.validity_scope.value == "fiscal_year"
        assert metadata.validity_basis.value == (
            "fiscal_year_rule"
        )
